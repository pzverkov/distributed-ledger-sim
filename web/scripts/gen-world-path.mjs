// Usage: node scripts/gen-world-path.mjs <ne_110m_land.geojson>
// Natural Earth 110m land (public domain), equirectangular, lat 85..-60, as one SVG path.
import { readFileSync, writeFileSync } from "node:fs";

const W = 800, LON = [-180, 180], LAT = [85, -60];
const X = lon => ((lon - LON[0]) / (LON[1] - LON[0])) * W;
const H = Math.round(((LAT[0] - LAT[1]) / (LON[1] - LON[0])) * W);
const Y = lat => ((LAT[0] - lat) / (LAT[0] - LAT[1])) * H;

const geo = JSON.parse(readFileSync(process.argv[2], "utf8"));
const polys = geo.features.flatMap(f =>
  f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates);
const d = polys.flatMap(p => p.map(ring =>
  "M" + ring.map(([lo, la]) => `${X(lo).toFixed(1)},${Y(Math.max(LAT[1], Math.min(LAT[0], la))).toFixed(1)}`).join("L") + "Z")).join("");

writeFileSync(new URL("../src/worldPath.ts", import.meta.url),
  `// Generated by scripts/gen-world-path.mjs from Natural Earth 110m land (public domain). Do not edit.\n` +
  `export const MAP_W = ${W};\nexport const MAP_H = ${H};\n` +
  `export const project = (lat: number, lon: number): [number, number] => [` +
  `Math.round(((lon - ${LON[0]}) / ${LON[1] - LON[0]}) * ${W}), ` +
  `Math.round(((${LAT[0]} - lat) / ${LAT[0] - LAT[1]}) * ${H})];\n` +
  `export const WORLD_PATH = "${d}";\n`);
console.log("height", H, "bytes", d.length);
